#!/usr/bin/env node
// Generate each eval case's self-contained `fixture.sh` from `scaffold.json` (docs/COST-BASELINE.md).
//
//   node scripts/build-eval-fixtures.mjs [--root <dir>] [--check]
//
// `claude plugin eval` starts every run in an empty workspace, and a scaffold script is not
// documented to see its case directory. So each script carries its files inline (base64) instead of
// copying them. The readable sources live in `plugins/<p>/evals/fixtures/`:
//
//   scaffold.json  { "fixture": "orders-api",        base tree under fixtures/
//                    "overlays": ["planned"],        written over it, from fixtures/overlays/<name>/
//                    "git": true,                    git init + one commit of the tree so far
//                    "after_commit": ["arch-change"] written after the commit: an uncommitted change
//                  }
// --check exits 1 when a committed fixture.sh is out of date with its sources.
import { readFileSync, writeFileSync, existsSync, readdirSync, chmodSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { walk } from './lib/repo.mjs';

function tree(dir) {
  if (!existsSync(dir)) throw new Error(`fixture directory not found: ${dir}`);
  return walk(dir).sort().map((f) => ({ rel: relative(dir, f), data: readFileSync(f) }));
}

const q = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

function writeFiles(files) {
  return files.map(({ rel, data }) => `put ${q(rel)} ${q(data.toString('base64'))}`).join('\n');
}

export function renderScaffold(fixturesDir, spec, caseName) {
  const base = tree(join(fixturesDir, spec.fixture));
  const overlays = (spec.overlays ?? []).flatMap((o) => tree(join(fixturesDir, 'overlays', o)));
  const after = (spec.after_commit ?? []).flatMap((o) => tree(join(fixturesDir, 'overlays', o)));
  const parts = [
    '#!/usr/bin/env bash',
    `# GENERATED by scripts/build-eval-fixtures.mjs from ${caseName}/scaffold.json. Do not edit.`,
    `# Fixture: ${spec.fixture}${spec.overlays?.length ? ` + ${spec.overlays.join(', ')}` : ''}${spec.after_commit?.length ? `; uncommitted: ${spec.after_commit.join(', ')}` : ''}`,
    'set -euo pipefail',
    'put() { mkdir -p "$(dirname "$1")"; printf %s "$2" | base64 -d > "$1"; }',
    writeFiles([...base, ...overlays]),
  ];
  if (spec.git) {
    parts.push(
      'git init -q -b main',
      'git -c user.name=eval -c user.email=eval@example.com add -A',
      'git -c user.name=eval -c user.email=eval@example.com commit -qm "fixture"',
    );
  }
  if (after.length) parts.push(writeFiles(after));
  return parts.join('\n') + '\n';
}

export function cases(root) {
  const out = [];
  const plugins = join(root, 'plugins');
  for (const p of readdirSync(plugins)) {
    const evals = join(plugins, p, 'evals');
    if (!existsSync(evals)) continue;
    for (const c of readdirSync(evals)) {
      const spec = join(evals, c, 'scaffold.json');
      if (existsSync(spec)) out.push({ evals, name: c, spec, script: join(evals, c, 'fixture.sh') });
    }
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--root');
  const root = resolve(i >= 0 ? args[i + 1] : process.cwd());
  const check = args.includes('--check');
  let stale = 0;
  for (const c of cases(root)) {
    const text = renderScaffold(join(c.evals, 'fixtures'), JSON.parse(readFileSync(c.spec, 'utf8')), c.name);
    const current = existsSync(c.script) ? readFileSync(c.script, 'utf8') : null;
    if (current === text) continue;
    if (check) {
      console.error(`  ✗ ${relative(root, c.script)} is out of date: run node scripts/build-eval-fixtures.mjs`);
      stale++;
    } else {
      writeFileSync(c.script, text);
      chmodSync(c.script, 0o755);
      console.log(`wrote ${relative(root, c.script)}`);
    }
  }
  if (check) console.log(stale ? `eval fixtures: ${stale} stale` : 'eval fixtures: up to date');
  process.exit(stale ? 1 : 0);
}

